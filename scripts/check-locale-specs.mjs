#!/usr/bin/env node
/**
 * check-locale-specs.mjs — issue #163's acceptance bar for the locale contract, derived from the
 * tree and never from a hand-kept list of components:
 *
 * 1. every `src/components/<name>/*.messages.ts` dictionary has a `test/<name>.spec.tsx` that calls
 *    the shared `describeLocales(...)` helper (`src/utils/locale.test-helpers.ts`);
 * 2. a component that calls `internals.setValidity(...)` passes `describeLocales` the `validity`
 *    option, so its message is proved to follow a locale change;
 * 3. `scripts/eslint/override-classes.json` classes every override `@Prop` (component -> prop ->
 *    `name` | `message` | `caption`), names no prop that is gone, and agrees with the source:
 *    the keys a component passes to `localeMessages(...)` as captions are exactly its caption props;
 * 4. each component's spec carries a test titled `empty <prop> falls back` (name, message) or
 *    `empty <prop> hides` (caption) for every override prop — written out, or generated by
 *    `describeLocales` from the prop listed in its `overrides` / `validity` options;
 * 5. the `mud-numeric-input` spec carries the `parse table` and `round trip` tests, with at least
 *    the rows the plan lists.
 *
 * Usage: node scripts/check-locale-specs.mjs
 */
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const COMPONENTS_DIR = path.join(ROOT, 'src/components');
const CLASSES_FILE = path.join(ROOT, 'scripts/eslint/override-classes.json');
const CLASS_VALUES = ['name', 'message', 'caption'];

/** Parse rows the numeric-input spec's `parse table` must carry (the plan's acceptance bar). */
const REQUIRED_PARSE_ROWS = [
  '1234,5',
  '1234.5',
  '1.234,5',
  '1,234.5',
  '1.234.567',
  '1,234,567',
  '1.5',
  '1,5',
  '1.234',
  '1,234',
];
/** The Unicode minus row, written either as the character or as an escape. */
const UNICODE_MINUS_ROW = /−\s*5|\\u2212\s*5/;
/** Values the `round trip` test must run. */
const REQUIRED_ROUND_TRIP_VALUES = ['1.234', '0.125', '1.5', '1234.5', '-0.5'];

const failures = [];
const fail = message => failures.push(`[check-locale-specs] ${message}`);

/** The text between the `(` at `open` and its matching `)`, ignoring parens inside strings. */
function balancedArguments(source, open) {
  let depth = 0;
  let quote = null;
  for (let i = open; i < source.length; i++) {
    const ch = source[i];
    if (quote) {
      if (ch === '\\') i++;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') quote = ch;
    else if (ch === '(') depth++;
    else if (ch === ')') {
      depth--;
      if (depth === 0) return source.slice(open + 1, i);
    }
  }
  return null;
}

/** Splits call arguments at top-level commas (brackets, braces, parens and strings nest). */
function splitArguments(text) {
  const parts = [];
  let depth = 0;
  let quote = null;
  let start = 0;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quote) {
      if (ch === '\\') i++;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === "'" || ch === '"' || ch === '`') quote = ch;
    else if ('([{'.includes(ch)) depth++;
    else if (')]}'.includes(ch)) depth--;
    else if (ch === ',' && depth === 0) {
      parts.push(text.slice(start, i));
      start = i + 1;
    }
  }
  parts.push(text.slice(start));
  return parts.map(part => part.trim()).filter(part => part.length > 0);
}

/** Every `localeMessages(...)` call in a component source: { overrideProps, captionKeys }. */
function localeMessagesCalls(source) {
  const calls = [];
  for (const match of source.matchAll(/\blocaleMessages\s*\(/g)) {
    const inner = balancedArguments(source, match.index + match[0].length - 1);
    if (inner === null) continue;
    // Line comments between arguments may hold quotes or backticks that would derail the split.
    const args = splitArguments(inner.replace(/\/\/.*$/gm, ''));
    const overrides = args[4] ?? '{}';
    const captions = args[5] ?? '[]';
    calls.push({
      overrideProps: [...overrides.matchAll(/\w+\s*:\s*this\.(\w+)/g)].map(m => m[1]),
      captionKeys: [...captions.matchAll(/['"](\w+)['"]/g)].map(m => m[1]),
      // `key: this.prop` pairs, so a caption key can be mapped back to the prop that feeds it.
      pairs: [...overrides.matchAll(/(\w+)\s*:\s*this\.(\w+)/g)].map(m => [m[1], m[2]]),
    });
  }
  return calls;
}

function main() {
  if (!fs.existsSync(COMPONENTS_DIR)) {
    console.error(`[check-locale-specs] ${COMPONENTS_DIR} does not exist.`);
    process.exit(1);
  }
  if (!fs.existsSync(CLASSES_FILE)) {
    console.error(`[check-locale-specs] ${path.relative(ROOT, CLASSES_FILE)} does not exist.`);
    process.exit(1);
  }
  const classes = JSON.parse(fs.readFileSync(CLASSES_FILE, 'utf8'));
  const dirs = fs
    .readdirSync(COMPONENTS_DIR)
    .filter(entry => fs.statSync(path.join(COMPONENTS_DIR, entry)).isDirectory())
    .sort();

  let checked = 0;
  let validityChecked = 0;
  let propsChecked = 0;
  for (const dir of dirs) {
    const dirPath = path.join(COMPONENTS_DIR, dir);
    const entries = fs.readdirSync(dirPath);
    const messageFiles = entries.filter(entry => entry.endsWith('.messages.ts'));
    if (messageFiles.length === 0) continue;
    checked++;

    const specPath = path.join(dirPath, 'test', `${dir}.spec.tsx`);
    if (!fs.existsSync(specPath)) {
      fail(`${dir}: has a *.messages.ts dictionary but no test/${dir}.spec.tsx.`);
      continue;
    }
    const spec = fs.readFileSync(specPath, 'utf8');
    // Matches both `describeLocales(...)` and the generic form `describeLocales<M>(...)`.
    const firstCall = spec.search(/\bdescribeLocales\s*[<(]/);
    if (firstCall === -1) {
      fail(`${dir}: test/${dir}.spec.tsx does not call describeLocales(...).`);
      continue;
    }
    const localeSpec = spec.slice(firstCall);

    const sources = entries
      .filter(entry => entry.endsWith('.tsx'))
      .map(entry => fs.readFileSync(path.join(dirPath, entry), 'utf8'));

    // 2. setValidity -> the `validity` option.
    if (sources.some(source => /\.setValidity\s*\(/.test(source))) {
      validityChecked++;
      if (!/\bvalidity\s*:/.test(localeSpec)) {
        fail(`${dir}: calls internals.setValidity(...) but its describeLocales(...) has no \`validity\` option.`);
      }
    }

    // 3. override-classes.json agrees with the source.
    const calls = sources.flatMap(localeMessagesCalls);
    const messageKeys = new Set();
    for (const file of messageFiles) {
      const text = fs.readFileSync(path.join(dirPath, file), 'utf8');
      const iface = text.match(/export interface \w+ \{([\s\S]*?)\n\}/);
      for (const key of iface?.[1].matchAll(/^\s{2}(\w+)\??:/gm) ?? []) messageKeys.add(key[1]);
    }
    const derived = new Set(calls.flatMap(call => call.overrideProps));
    // An override prop the component handles outside `localeMessages` (a template it fills itself):
    // any `@Prop` named like a dictionary key.
    for (const source of sources) {
      for (const prop of source.matchAll(/@Prop\([^)]*\)\s*(\w+)/g)) if (messageKeys.has(prop[1])) derived.add(prop[1]);
    }
    const classed = classes[dir] ?? {};
    for (const prop of derived) {
      if (!(prop in classed)) fail(`${dir}: override prop "${prop}" has no class in override-classes.json.`);
    }
    for (const [prop, cls] of Object.entries(classed)) {
      if (!CLASS_VALUES.includes(cls))
        fail(`${dir}.${prop}: class "${cls}" is not one of ${CLASS_VALUES.join(' | ')}.`);
      if (!derived.has(prop))
        fail(`${dir}: override-classes.json names "${prop}", which is no override prop of the component.`);
    }
    if (derived.size === 0 && Object.keys(classed).length > 0) fail(`${dir}: has classes but no override props.`);

    // The captions handed to `localeMessages` are exactly the caption props that feed it.
    const captionProps = new Set(
      Object.entries(classed)
        .filter(([, cls]) => cls === 'caption')
        .map(([prop]) => prop),
    );
    for (const call of calls) {
      const keyToProp = new Map(call.pairs);
      for (const key of call.captionKeys) {
        const prop = keyToProp.get(key);
        if (!prop) fail(`${dir}: localeMessages(...) lists caption key "${key}" that no override feeds.`);
        else if (!captionProps.has(prop)) {
          fail(
            `${dir}: localeMessages(...) treats "${prop}" as a caption; override-classes.json says ${classed[prop] ?? 'nothing'}.`,
          );
        }
      }
      for (const [key, prop] of call.pairs) {
        if (captionProps.has(prop) && !call.captionKeys.includes(key)) {
          fail(
            `${dir}: caption prop "${prop}" (key ${key}) is not in the captions list of its localeMessages(...) call.`,
          );
        }
      }
    }

    // 4. one `empty <prop> falls back|hides` test per override prop.
    for (const [prop, cls] of Object.entries(classed)) {
      propsChecked++;
      const verb = cls === 'caption' ? 'hides' : 'falls back';
      const other = cls === 'caption' ? 'falls back' : 'hides';
      if (new RegExp(`empty ${prop} ${other}`).test(spec) && !new RegExp(`empty ${prop} ${verb}`).test(spec)) {
        fail(
          `${dir}: test "empty ${prop} ${other}" is the wrong verb for a ${cls} — expected "empty ${prop} ${verb}".`,
        );
        continue;
      }
      if (new RegExp(`empty ${prop} ${verb}`).test(spec)) continue;
      // Generated by describeLocales from the prop named in its `overrides` / `validity` options.
      const named = new RegExp(`['"]${prop}['"]`).test(localeSpec);
      if (!named) {
        fail(
          `${dir}: no test "empty ${prop} ${verb}" — write it, or list "${prop}" in describeLocales(...) overrides / validity.`,
        );
      } else if (cls === 'caption' && !/\bcaptions\s*:/.test(localeSpec)) {
        fail(`${dir}: caption "${prop}" is generated by describeLocales, but its call has no \`captions\` option.`);
      }
    }
  }

  // 5. the numeric-input tables.
  const numericSpec = path.join(COMPONENTS_DIR, 'mud-numeric-input/test/mud-numeric-input.spec.tsx');
  if (fs.existsSync(numericSpec)) {
    const text = fs.readFileSync(numericSpec, 'utf8');
    for (const title of ['parse table', 'round trip']) {
      if (!text.includes(title)) fail(`mud-numeric-input: spec has no test titled "${title}".`);
    }
    const parseStart = text.indexOf('parse table');
    const roundStart = text.indexOf('round trip');
    if (parseStart !== -1) {
      // The rows are data declared above the `parse table` describe that runs them.
      const block = text.slice(0, roundStart > parseStart ? roundStart : undefined);
      for (const row of REQUIRED_PARSE_ROWS) {
        if (!block.includes(`'${row}'`)) fail(`mud-numeric-input: parse table has no row for '${row}'.`);
      }
      if (!UNICODE_MINUS_ROW.test(block))
        fail('mud-numeric-input: parse table has no row for the Unicode minus (U+2212).');
      if (!/ambiguous/i.test(block)) fail('mud-numeric-input: parse table does not assert the ambiguous case.');
    }
    if (roundStart !== -1) {
      const block = text.slice(roundStart);
      for (const value of REQUIRED_ROUND_TRIP_VALUES) {
        if (!block.includes(value)) fail(`mud-numeric-input: round trip table has no value ${value}.`);
      }
      if (!block.includes('formStateRestoreCallback'))
        fail('mud-numeric-input: round trip does not call formStateRestoreCallback.');
    }
  } else {
    fail('mud-numeric-input: test/mud-numeric-input.spec.tsx does not exist.');
  }

  if (failures.length > 0) {
    for (const message of failures) console.error(message);
    console.error(`[check-locale-specs] FAILED — ${failures.length} problem(s), see rows above.`);
    process.exit(1);
  }
  console.log(
    `[check-locale-specs] OK — ${checked} component(s) with a *.messages.ts call describeLocales(...); ` +
      `${validityChecked} calling setValidity pass \`validity\`; ${propsChecked} override props classed and tested.`,
  );
}

main();
