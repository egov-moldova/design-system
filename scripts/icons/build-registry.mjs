#!/usr/bin/env node
/**
 * Scan src/components/mud-icon/assets/{outlined,filled}/*.svg and emit:
 *   - icons.manifest.json — public surface (API name → styles available)
 *   - ../icon-names.ts    — the same names as a literal tuple + `IconName` union,
 *                           so props typed `IconName` reject unknown names at
 *                           compile time. Literal TS (not `keyof typeof` the JSON)
 *                           because the emitted `.d.ts` cannot resolve the JSON.
 *
 * `--check` writes nothing and exits 1 when either file differs from what this
 * scan would emit (run by src/components/mud-icon/test/icon-names.spec.ts).
 *
 * SVGs are served as individual static assets (lazy-loaded on demand). One
 * drawing per style covers every size — `mud-icon` scales it through `size`.
 *
 * Naming:
 *   The style lives in the directory, never in the filename. A file whose name
 *   still carries a `-filled` / `-fill` / `-solid` suffix is a leftover of the
 *   per-size layout and fails the run rather than producing `car-filled` inside
 *   assets/filled/.
 */
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PROJECT_ROOT = path.resolve(__dirname, '..', '..');
const ASSETS_ROOT = path.join(PROJECT_ROOT, 'src/components/mud-icon/assets');
const MANIFEST_JSON = path.join(ASSETS_ROOT, 'icons.manifest.json');
const ICON_NAMES_TS = path.join(ASSETS_ROOT, '..', 'icon-names.ts');

const VARIANTS = ['outlined', 'filled'];
const SAFE_ICON_NAME = /^[a-z][a-z0-9-]*$/;
const STYLE_SUFFIX = /-(filled|fill|solid)$/;
/** `--check`: compare the would-be outputs with the files on disk, write nothing. */
const CHECK_ONLY = process.argv.includes('--check');

function renderIconNamesModule(names, filledNames, filledOnlyNames) {
  return [
    '// Generated by scripts/icons/build-registry.mjs from the SVGs in assets/ — do not edit.',
    '',
    'export const ICON_NAMES = [',
    ...names.map(name => `  '${name}',`),
    '] as const;',
    '',
    '/** Every icon name `mud-icon` can render. */',
    'export type IconName = (typeof ICON_NAMES)[number];',
    '',
    '/** The subset drawn in the filled style. */',
    'export const FILLED_ICON_NAMES = [',
    ...filledNames.map(name => `  '${name}',`),
    '] as const;',
    '',
    '/** Drawn in the filled style ONLY — these have no outlined drawing. */',
    'export const FILLED_ONLY_ICON_NAMES = [',
    ...filledOnlyNames.map(name => `  '${name}',`),
    '] as const;',
    '',
    'const ICON_NAME_SET: ReadonlySet<string> = new Set(ICON_NAMES);',
    'const FILLED_NAME_SET: ReadonlySet<string> = new Set(FILLED_ICON_NAMES);',
    'const FILLED_ONLY_NAME_SET: ReadonlySet<string> = new Set(FILLED_ONLY_ICON_NAMES);',
    '',
    '/** Runtime guard for names that arrive untyped (HTML attributes, JSON data). */',
    'export function isIconName(value: unknown): value is IconName {',
    "  return typeof value === 'string' && ICON_NAME_SET.has(value);",
    '}',
    '',
    '/**',
    ' * Whether an icon is drawn in a given style. Answers from these two sets rather',
    ' * than from the manifest, so a caller does not pull the whole registry into its',
    ' * bundle — and so a name like `constructor` cannot reach a prototype member.',
    ' */',
    "export function hasIconVariant(name: unknown, variant: 'outlined' | 'filled'): boolean {",
    '  if (!isIconName(name)) return false;',
    "  return variant === 'filled' ? FILLED_NAME_SET.has(name) : !FILLED_ONLY_NAME_SET.has(name);",
    '}',
    '',
  ].join('\n');
}

async function main() {
  /** @type {Map<string, Set<string>>} API name → styles it is drawn in */
  const collected = new Map();
  const suffixed = [];

  for (const variant of VARIANTS) {
    const dir = path.join(ASSETS_ROOT, variant);
    let files;
    try {
      files = await fs.readdir(dir);
    } catch (err) {
      if (err.code === 'ENOENT') {
        throw new Error(`[icons] missing asset directory: ${path.relative(PROJECT_ROOT, dir)}`);
      }
      throw err;
    }

    for (const file of files) {
      if (!file.endsWith('.svg')) continue;
      const name = file.replace(/\.svg$/, '');
      if (STYLE_SUFFIX.test(name)) {
        suffixed.push(`${variant}/${file}`);
        continue;
      }
      const variants = collected.get(name) ?? new Set();
      variants.add(variant);
      collected.set(name, variants);
    }
  }

  if (suffixed.length) {
    throw new Error(`[icons] style suffix in a filename — the directory carries the style now: ${suffixed.join(', ')}`);
  }

  // The producers in this folder still write `assets/<size>/`. Nothing else
  // would notice: this scan reads only the two style directories, so a re-run of
  // the Figma download would recreate the old layout beside the new one and
  // `--check` would stay green over it.
  const unexpected = (await fs.readdir(ASSETS_ROOT, { withFileTypes: true }))
    .filter(entry => entry.isDirectory() && !VARIANTS.includes(entry.name))
    .map(entry => entry.name);
  if (unexpected.length) {
    throw new Error(
      `[icons] unexpected directory under assets/: ${unexpected.join(', ')} — the style directories ` +
        `(${VARIANTS.join(', ')}) are the whole layout now.`,
    );
  }

  const sortedNames = [...collected.keys()].sort();
  if (!sortedNames.length) throw new Error('[icons] no SVG assets found');

  const manifest = {};
  for (const name of sortedNames) {
    manifest[name] = { variants: VARIANTS.filter(variant => collected.get(name).has(variant)) };
  }

  // Names are interpolated into TypeScript source, so a filename outside this
  // alphabet could inject code into icon-names.ts. Refuse the whole run.
  const unsafe = sortedNames.filter(name => !SAFE_ICON_NAME.test(name));
  if (unsafe.length) {
    throw new Error(`[icons] refusing unsafe icon name(s): ${unsafe.map(n => JSON.stringify(n)).join(', ')}`);
  }

  const outputs = [
    [MANIFEST_JSON, JSON.stringify(manifest, null, 2) + '\n'],
    [
      ICON_NAMES_TS,
      renderIconNamesModule(
        sortedNames,
        sortedNames.filter(name => collected.get(name).has('filled')),
        sortedNames.filter(name => !collected.get(name).has('outlined')),
      ),
    ],
  ];

  if (CHECK_ONLY) {
    const stale = [];
    for (const [file, expected] of outputs) {
      const actual = await fs.readFile(file, 'utf8').catch(() => null);
      if (actual !== expected) stale.push(path.relative(PROJECT_ROOT, file));
    }
    if (stale.length) {
      console.error(`[icons] out of date: ${stale.join(', ')} — run node scripts/icons/build-registry.mjs`);
      process.exit(1);
    }
    console.log('[icons] manifest and icon-names.ts are up to date');
    return;
  }

  for (const [file, content] of outputs) {
    await fs.writeFile(file, content, 'utf8');
  }

  const perVariant = VARIANTS.reduce((acc, variant) => {
    acc[variant] = sortedNames.filter(name => collected.get(name).has(variant)).length;
    return acc;
  }, {});

  const offGrid = [];
  for (const variant of VARIANTS) {
    for (const name of sortedNames) {
      if (!collected.get(name).has(variant)) continue;
      const head = (await fs.readFile(path.join(ASSETS_ROOT, variant, `${name}.svg`), 'utf8')).slice(0, 400);
      const viewBox = head.match(/viewBox="0 0 (\d+(?:\.\d+)?) /);
      if (viewBox && viewBox[1] !== '24') offGrid.push(`${variant}/${name} (${viewBox[1]})`);
    }
  }
  if (offGrid.length) {
    // Not a refusal: these render, they just carry a different stroke weight
    // when scaled to the same box as a 24-grid drawing. Redrawing them is a
    // design call, so this names them rather than deciding for the designer.
    console.warn(`[icons] ${offGrid.length} drawing(s) not on the 24 grid: ${offGrid.join(', ')}`);
  }

  console.log(`[icons] Manifest built — ${sortedNames.length} icons:`);
  for (const variant of VARIANTS) {
    console.log(`  ${variant}: ${perVariant[variant]} icons`);
  }
  console.log(`[icons] Wrote ${path.relative(PROJECT_ROOT, MANIFEST_JSON)}`);
  console.log(`[icons] Wrote ${path.relative(PROJECT_ROOT, ICON_NAMES_TS)}`);
}

main().catch(err => {
  console.error(err);
  process.exit(1);
});
